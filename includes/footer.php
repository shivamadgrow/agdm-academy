  function refreshCaptcha(btn) {
    const icon = btn.querySelector('i');
    if (icon) {
      icon.style.transition = 'transform 0.5s ease';
      icon.style.transform = 'rotate(360deg)';
    }
    
    // Target all captcha elements on page (keeps multiple forms in sync)
    fetch('refresh_captcha.php')
      .then(response => response.json())
      .then(data => {
        if (data.status === 'success') {
          document.querySelectorAll('#captcha-question-addon').forEach(el => {
            el.textContent = data.question;
          });
          document.querySelectorAll('#agdm_captcha').forEach(el => {
            el.value = '';
          });
        }
      })
      .catch(err => console.error('Error refreshing captcha:', err))
      .finally(() => {
        if (icon) {
          setTimeout(() => {
            icon.style.transform = 'none';
          }, 500);
        }
      });
  }
